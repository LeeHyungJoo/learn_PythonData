DROP TABLE SHARES;
DROP TABLE CUSTOMER;
DROP TABLE STOCK;

CREATE TABLE CUSTOMER
       (SSN VARCHAR2(20) NOT NULL,
       CUST_NAME VARCHAR2(40) NOT NULL,
       ADDRESS VARCHAR2(100) NOT NULL ,
       PRIMARY KEY (SSN)) ;

CREATE TABLE STOCK
       (SYMBOL VARCHAR2(30) NOT NULL,
       PRICE NUMBER(10,2) NOT NULL,
        PRIMARY KEY (SYMBOL)) ;

CREATE TABLE SHARES
       (SSN VARCHAR2(20) NOT NULL,
       SYMBOL VARCHAR2(30) NOT NULL,
       QUANTITY NUMBER(10,0) NOT NULL,
       CONSTRAINT FK_SSN  FOREIGN KEY (SSN) REFERENCES  CUSTOMER,
       CONSTRAINT FK_SYMBOL FOREIGN KEY (SYMBOL)  REFERENCES  STOCK) ;


